import { Injectable, computed, inject, signal } from '@angular/core';
import type { ChatNode } from '../../models/chat';
import { ChatService } from '../chat/chat.service';
import { ProjectService } from '../settings/project.service';
import { PromptDefaultsService } from '../prompts/prompt-defaults.service';
import {
  chapterPlanLabel,
  chapterPlanOf,
  type ChapterPlan,
} from '../llm/chapter-plan';

/** A node that can serve as the chapter plan of an elaboration. */
export interface ElaboratePlanCandidate {
  node: ChatNode;
  plan: ChapterPlan;
  /** "7–16, 10" — first–last, entry count. */
  label: string;
}

/** Per-chat continuation state remembered for the Elaborate dialog. */
export interface ElaborateState {
  lastChapter: number;
  characters: string;
  hints: string;
  prefix: string;
  /** “Add the chapter descriptions to the lore” for this chat. */
  usePlan?: boolean;
  /**
   * True when the user EXPLICITLY unchecked the chapter-plan option. The
   * dialog defaults it to ON whenever the chat has a usable plan, so only a
   * deliberate opt-out must be remembered (an older stored `usePlan: false`
   * was the silent default and keeps the new default-on behaviour).
   */
  usePlanOff?: boolean;
  /**
   * How many chapter descriptions travel with each elaboration IN TOTAL,
   * starting at the elaborated chapter (1 = only that chapter).
   */
  planChapters?: number;
  /**
   * @deprecated Legacy pre-2026-11 field: the number of FOLLOWING chapters
   * (total = planFollowing + 1). Only read to migrate old stored state; never
   * written any more.
   */
  planFollowing?: number;
  /** Node id of the chosen plan (null = the newest one). */
  planNodeId?: string | null;
}

/**
 * Owns the open state of the Elaborate dialog (first/last chapter + names +
 * prefix + hints + stick-to-last + model) and its per-chat localStorage
 * persistence — the dialog STATE that used to live inside ChatComponent.
 * Mirrors the dialog services in this folder (IllustrateDialogService /
 * PrependDialogService / LightboxService): the state lives here; the LLM
 * orchestration that `confirmElaborate()` runs stays in the component and
 * reads/writes through this service.
 */
@Injectable({ providedIn: 'root' })
export class ChatElaborateDialogService {
  /** Per-chat Elaborate continuation state (localStorage). */
  private static readonly LS_ELABORATE = 'chat-client.elaborate.byChatId';
  /** Default for `planChapters`: the elaborated chapter + the next one (this
   *  equals the old default of "1 following chapter"). */
  static readonly DEFAULT_PLAN_CHAPTERS = 2;

  private readonly chatService = inject(ChatService);
  private readonly projectService = inject(ProjectService);
  private readonly promptDefaults = inject(PromptDefaultsService);

  readonly show = signal(false);
  readonly first = signal(1);
  readonly last = signal(1);
  readonly names = signal('');
  readonly prefix = signal('');
  readonly hints = signal('');
  /** When checked, the dialog ignores First/Last and re-elaborates the chapter
   *  that was last elaborated, chaining onto its already generated text. */
  readonly stickLast = signal(false);
  /** Model used for every elaboration. Initialised to the model of the most
   *  recent assistant answer; can be overridden in the dialog. */
  readonly modelId = signal<string>('');

  /**
   * “Add the chapter descriptions to the lore”: while checked, every
   * elaboration send carries the matching chapter-plan entry PLUS enough
   * following entries to reach `planChapters` descriptions as a TEMPORARY lore
   * section (nothing is written to `chat.lore`).
   */
  readonly usePlan = signal(false);
  /**
   * TOTAL number of chapter descriptions per send, starting at the elaborated
   * chapter (1 = only that chapter). The dialog field shows exactly this number
   * — what the user types is the number of chapters added to the lore.
   */
  readonly planChapters = signal(ChatElaborateDialogService.DEFAULT_PLAN_CHAPTERS);
  /** Explicitly chosen plan node (null = newest plan found in the chat). */
  readonly planNodeId = signal<string | null>(null);

  /**
   * Nodes of the current chat that can serve as a chapter plan.
   *
   * ONLY the CURRENTLY VISIBLE THREAD is considered: candidates come from the
   * active path (root → active leaf), never from branches the user navigated
   * away from. A plan sitting on an abandoned branch must not be picked up —
   * "newest in the whole chat" is exactly how strange chapter lists appeared.
   *
   * A node qualifies when it carries a stored `chapter-plan.json` record
   * (generated by the chapter-description flow, parsed and validated at
   * generation time) OR when its own text IS a real outline —
   * `chapterPlanFromText` requires the FIRST line to be a numbered item and
   * every entry to carry a description, so a prose chapter that merely
   * contains an enumeration never competes. The text rule is not a convenience
   * heuristic: the record lives only on the ANSWER node, so an outline whose
   * answer was regenerated / rewritten before the record was re-derived had no
   * record at all — and the old "only fall back when the chat has NO record"
   * rule then hid every later outline as soon as ONE outline had a record
   * ("a second chapter outline is not recognized by elaborate"). The newest
   * candidate wins by default.
   */
  readonly planCandidates = computed<ElaboratePlanCandidate[]>(() => {
    const assistantNodes = this.chatService
      .getActivePath()
      .filter(node => node.role === 'assistant');

    const candidates: ElaboratePlanCandidate[] = [];
    for (const node of assistantNodes) {
      const plan = chapterPlanOf(node);
      if (!plan || plan.entries.length < 2) continue;
      candidates.push({ node, plan, label: chapterPlanLabel(plan) });
    }

    return candidates.sort((a, b) =>
      (b.node.createdAt ?? '').localeCompare(a.node.createdAt ?? ''),
    );
  });

  /** The plan in effect: the chosen node, else the newest candidate. */
  readonly activePlan = computed<ChapterPlan | null>(() => {
    const candidates = this.planCandidates();
    if (candidates.length === 0) return null;
    const chosen = this.planNodeId();
    const match = chosen ? candidates.find(c => c.node.id === chosen) : null;
    return (match ?? candidates[0]).plan;
  });

  /** "7–16, 10" of the plan in effect ('' when there is none). */
  readonly activePlanLabel = computed<string>(() => chapterPlanLabel(this.activePlan()));

  /**
   * Whether the active plan covers AT LEAST ONE of the requested chapters.
   * When false, nothing would be added to the lore — the dialog says so.
   */
  readonly planCoversRange = computed<boolean>(() => {
    const plan = this.activePlan();
    if (!plan) return false;
    const first = Math.max(this.first(), 1);
    const last = Math.max(this.last(), first);
    return plan.entries.some(e => e.chapter >= first && e.chapter <= last);
  });

  /**
   * Live preview of the FIRST elaboration prompt that confirmElaborate() will
   * send — mirrors its template/vars selection (topic-scoped), so the user
   * sees the actual prompt before confirming. Reactive to every dialog input.
   */
  readonly preview = computed<{
    text: string;
    templateLabel: string;
    count: number;
  } | null>(() => {
    const chatId = this.chatService.currentChatId();
    if (!chatId) return null;
    const topicId = this.topicId(chatId);
    const prefix = this.prefix().trim();
    const hints = this.hintsText();
    const names = this.names()
      .split(',')
      .map(s => s.trim())
      .filter(Boolean);

    // Chapter actually used for the FIRST prompt ("stick to last" resolves to
    // the stored last chapter of this chat, like confirmElaborate() does).
    let first = Math.max(this.first(), 1);
    let last = this.last();
    if (this.stickLast()) {
      const state = this.loadState(chatId);
      const stick = state.lastChapter > 0 ? state.lastChapter : Math.max(last, 1);
      first = stick;
      last = stick;
    }

    const template = names.length > 0 ? 'structure.elaborate-view' : 'structure.elaborate';
    const vars = {
      chapter: `${prefix}${first}`,
      hints,
      ...(names.length > 0 ? { name: names[0], isFirst: !this.stickLast() } : {})
    };
    const text = this.promptDefaults.render(template, vars, topicId);
    const chapters = Math.max(last - first + 1, 1);
    const count = names.length > 0 ? names.length * chapters : chapters;
    return {
      text,
      templateLabel: this.promptDefaults.def(template)?.label ?? template,
      count
    };
  });

  /** Per-chat continuation state for the Elaborate dialog. */
  loadState(chatId: string): ElaborateState {
    try {
      const raw = localStorage.getItem(ChatElaborateDialogService.LS_ELABORATE);
      const map = raw ? JSON.parse(raw) : {};
      const entry = map?.[chatId];
      if (entry && typeof entry.lastChapter === 'number' && Number.isFinite(entry.lastChapter)) {
        return {
          lastChapter: Math.max(0, Math.floor(entry.lastChapter)),
          characters: typeof entry.characters === 'string' ? entry.characters : '',
          hints: typeof entry.hints === 'string' ? entry.hints : '',
          prefix: typeof entry.prefix === 'string' ? entry.prefix : '',
          usePlan: entry.usePlan === true,
          usePlanOff: entry.usePlanOff === true,
          planChapters: this.readPlanChapters(entry),
          planNodeId: typeof entry.planNodeId === 'string' ? entry.planNodeId : null,
        };
      }
    } catch {
      /* corrupted / blocked storage — start fresh */
    }
    return {
      lastChapter: 0,
      characters: '',
      hints: '',
      prefix: '',
      usePlan: true,
      usePlanOff: false,
      planChapters: ChatElaborateDialogService.DEFAULT_PLAN_CHAPTERS,
      planNodeId: null,
    };
  }

  /**
   * TOTAL plan chapters per send from a stored entry: the current field, else
   * the legacy "following" count + 1 (0/1 following = 1/2 total), else the
   * default. Clamped to a sane 1..50.
   */
  private readPlanChapters(entry: Record<string, unknown>): number {
    const total =
      typeof entry['planChapters'] === 'number' && Number.isFinite(entry['planChapters'])
        ? entry['planChapters']
        : typeof entry['planFollowing'] === 'number' && Number.isFinite(entry['planFollowing'])
          ? (entry['planFollowing'] as number) + 1
          : ChatElaborateDialogService.DEFAULT_PLAN_CHAPTERS;
    return Math.min(50, Math.max(1, Math.floor(total as number)));
  }

  /** Clamp the "plan chapters" input (1..50) — templates cannot use Math. */
  setPlanChapters(value: number | string): void {
    const n = Math.floor(Number(value));
    this.planChapters.set(Number.isFinite(n) ? Math.min(50, Math.max(1, n)) : 1);
  }

  saveState(chatId: string, state: ElaborateState): void {
    try {
      const raw = localStorage.getItem(ChatElaborateDialogService.LS_ELABORATE);
      const map = raw ? JSON.parse(raw) : {};
      map[chatId] = state;
      localStorage.setItem(ChatElaborateDialogService.LS_ELABORATE, JSON.stringify(map));
    } catch {
      /* best-effort; never block elaboration on storage failure */
    }
  }

  /** The dialog hints formatted for the `{{hints}}` template placeholder
   *  (empty string when no hints were given, so empty templates stay clean). */
  hintsText(): string {
    const hints = this.hints().trim();
    return hints ? `\nFollow these hints from the user: ${hints}` : '';
  }

  /** Topic-scoped prompt versions apply to the chat's environment topic. */
  topicId(chatId: string | null): string | null {
    const chat = chatId
      ? this.chatService.chats().find(c => c.id === chatId) ?? null
      : null;
    const project = chat?.projectId
      ? this.projectService.getProject(chat.projectId) ?? null
      : null;
    return this.projectService
      .topicForProject(project?.id, this.projectService.topics())?.id ?? null;
  }

  /** Toggle "stick to last chapter". While checked the First/Last fields are
   *  disabled and shown as the single chapter last elaborated for this chat;
   *  unchecking restores the default continuation (= last elaborated + 1). */
  onStickLastToggle(checked: boolean, chatId: string | null): void {
    this.stickLast.set(!!checked);
    if (!chatId) return;
    const state = this.loadState(chatId);
    if (checked) {
      const stick = state.lastChapter > 0
        ? state.lastChapter
        : Math.max(this.last(), 1);
      this.first.set(stick);
      this.last.set(stick);
      // Sticking to the last chapter re-elaborates existing text, so any
      // characters/hints only make sense for fresh chapters — clear them.
      this.names.set('');
      this.hints.set('');
    } else {
      const next = Math.max(state.lastChapter + 1, 1);
      this.first.set(next);
      this.last.set(next);
    }
  }

  /** Close the dialog (used by Cancel and Escape). */
  close(): void {
    this.show.set(false);
  }
}